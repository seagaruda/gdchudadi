// 把 android/app/build.gradle 的 versionName 寫進 src/version.js，
// 讓 App 內「說明頁」底部的版本號與實際 APK 版本一致。
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const gradle = fs.readFileSync(path.join(root, 'android/app/build.gradle'), 'utf8');
const m = gradle.match(/versionName\s+"([^"]+)"/);
if (!m) {
    console.error('[Stem-version] versionName not found in build.gradle');
    process.exit(1);
}
const version = m[1];
const full = `${version}.0`;

const pkgPath = path.join(root, 'package.json');
if (fs.existsSync(pkgPath)) {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    pkg.version = version;
    if (!pkg.build) pkg.build = {};
    pkg.build.buildVersion = full;
    fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2));
}

const out = `// Automatically generated by stamp-version.js. Do not edit.\nwindow.AppVersionInfo = {\n  version: "${version}",\n  buildVersion: "${full}",\n  author: "mesmerli"\n};\n`;
fs.writeFileSync(path.join(root, 'src/version.js'), out);
console.log(`[Stamp-version] src/version.js -> ${version} (${full})`);
