const fs = require('fs');
const path = require('path');

const packagePath = path.join(__dirname, '..', 'package.json');
const packageJson = JSON.parse(fs.readFileSync(packagePath, 'utf8'));

let versionParts = packageJson.version.split('.');
const majorMinor = versionParts.slice(0, 2).join('.'); // "1.1"

// Use the 3rd part for build number because Microsoft Store requires 4th part to be 0
let currentBuild = parseInt(packageJson.build.buildNumber || "0");
let nextBuild = currentBuild + 1;


const baseVersion = `${majorMinor}.${nextBuild}`; // "1.1.1107"
const fullVersion = `${baseVersion}.0`; // "1.1.1107.0"

packageJson.version = baseVersion;
packageJson.build.buildVersion = fullVersion;
packageJson.build.buildNumber = nextBuild.toString();
packageJson.buildTarget = process.env.BUILD_TARGET || 'GITHUB';

// Manually update artifactName to avoid env variable issues
if (packageJson.build && packageJson.build.win) {
    packageJson.build.win.artifactName = `${packageJson.build.productName}_${fullVersion}.\${ext}`;
}




fs.writeFileSync(packagePath, JSON.stringify(packageJson, null, 2));
console.log(`Version: ${baseVersion}, BuildVersion: ${fullVersion}, Updated artifactName.`);

// 2. 自动同步更新 tauri.conf.json 版本号
const tauriConfPath = path.join(__dirname, '..', 'src-tauri', 'tauri.conf.json');
if (fs.existsSync(tauriConfPath)) {
    try {
        const tauriConf = JSON.parse(fs.readFileSync(tauriConfPath, 'utf8'));
        tauriConf.version = baseVersion;
        fs.writeFileSync(tauriConfPath, JSON.stringify(tauriConf, null, 2), 'utf8');
        console.log(`[Sync] tauri.conf.json 版本号已同步更新为: ${baseVersion}`);
    } catch (err) {
        console.error(`[Sync] 更新 tauri.conf.json 失败:`, err);
    }
}

// 3. 自动产生与更新 src/version.js 版本资讯档
const versionJsPath = path.join(__dirname, '..', 'src', 'version.js');
try {
    const versionJsContent = `// Automatically generated by increment-build.js. Do not edit.
window.AppVersionInfo = {
  version: "${baseVersion}",
  buildVersion: "${fullVersion}",
  author: "${packageJson.author || 'SeaGaruda'}"
};
`;
    fs.writeFileSync(versionJsPath, versionJsContent, 'utf8');
    console.log(`[Sync] src/version.js 已同步更新为: ${baseVersion}`);
} catch (err) {
    console.error(`[Sync] 更新 src/version.js 失败:`, err);
}



